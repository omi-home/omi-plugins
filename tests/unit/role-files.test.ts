// DevTask-0054 #167: role files of a task workspace come from agents/<role>.md and the report
// templates; every role's rule pack resolves.
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { Role } from "../../runtime/core/contracts.ts";
import { writeRoleFiles } from "../../runtime/resources/role-files.ts";

const pluginRoot = fileURLToPath(new URL("../../", import.meta.url));

test("every role gets AGENTS.md (its rule pack), REPORT.md and settings; rewritten per role", () => {
  const taskRoot = mkdtempSync(join(tmpdir(), "omi-role-"));
  for (const role of Role.options) {
    writeRoleFiles({ taskRoot, pluginRoot, role, category: "review", edits: false });
    const agents = readFileSync(join(taskRoot, "AGENTS.md"), "utf8");
    assert.match(agents, new RegExp(`^<!-- Generated by OMI for role ${role};`));
    assert.doesNotMatch(agents, /CLAUDE_PLUGIN_ROOT/, role);
  }
  writeRoleFiles({
    taskRoot,
    pluginRoot,
    role: "backend-engineer",
    category: "implementation",
    edits: true,
  });
  const agents = readFileSync(join(taskRoot, "AGENTS.md"), "utf8");
  const rule = readFileSync(
    join(pluginRoot, "resources/role-rules/backend/backend-implementation.md"),
    "utf8",
  );
  assert.ok(agents.includes(rule.trim()));
  assert.equal(
    readFileSync(join(taskRoot, "REPORT.md"), "utf8"),
    readFileSync(join(pluginRoot, "templates/reports/implementation.md"), "utf8"),
  );
  assert.deepEqual(JSON.parse(readFileSync(join(taskRoot, ".claude", "settings.json"), "utf8")), {
    permissions: { defaultMode: "acceptEdits" },
  });
});
