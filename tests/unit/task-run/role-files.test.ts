// DevTask-0054 #167, DevTask-0065 #199: role files of a task workspace: AGENTS.md (rules only),
// REPORT.md, settings, and only the skills chosen for the step in `.claude/skills/`.
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readdirSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { Role } from "../../../runtime/shared/contracts.ts";
import {
  parseSkillChoice,
  roleSkills,
  skillList,
  stepSkills,
  writeRoleFiles,
} from "../../../runtime/task-run/adapters/role-files.ts";

const pluginRoot = fileURLToPath(new URL("../../../", import.meta.url));
const installed = (taskRoot: string) => readdirSync(join(taskRoot, ".claude", "skills")).sort();

test("every role gets AGENTS.md, REPORT.md, settings and its default skills; rewritten per role", () => {
  const taskRoot = mkdtempSync(join(tmpdir(), "omi-role-"));
  for (const role of Role.options) {
    writeRoleFiles({ taskRoot, pluginRoot, role, category: "review", edits: false, repo: "app" });
    const agents = readFileSync(join(taskRoot, "AGENTS.md"), "utf8");
    assert.ok(agents.startsWith("<!-- Generated by OMI; rewritten before every run. -->\n# OMI"));
    const part = readFileSync(join(pluginRoot, "agent-pack/agents-md", `${role}.md`), "utf8");
    assert.ok(agents.includes(part.trim()), role);
    assert.doesNotMatch(agents, /CLAUDE_PLUGIN_ROOT|Pack-ID/, role);
    assert.deepEqual(installed(taskRoot), [...roleSkills(pluginRoot, role).default].sort(), role);
  }
  writeRoleFiles({
    taskRoot,
    pluginRoot,
    role: "software-engineer",
    category: "implementation",
    edits: true,
    repo: "app",
    checks: ["npm run lint", "npm test"],
  });
  const agents = readFileSync(join(taskRoot, "AGENTS.md"), "utf8");
  assert.ok(agents.includes("`git -C app <command>`"));
  // #252: the rules name exactly the granted checks, never a generic `cd app && <command>`.
  assert.ok(agents.includes("`cd app && npm run lint`, `cd app && npm test`"));
  assert.ok(!agents.includes("`cd app && <command>`"));
  // #275: one check per command, and the bare form once the cwd is already in the repo.
  assert.ok(agents.includes("no `;`, no pipes"));
  assert.ok(agents.includes("run the bare check (e.g. `npm run lint`)"));
  // CR-001: no claim that every Bash call starts in the workspace; bare read-only git once inside the repo.
  assert.ok(!agents.includes("Every Bash call starts in this workspace"));
  assert.ok(
    agents.includes(
      "run read-only git bare there (`git status`, `git diff`, `git log`, `git show`)",
    ),
  );
  // DevTask-0131 #382: the engineer is told it may `git mv` and run the repo's npm scripts.
  assert.ok(agents.includes("`git -C app mv`"));
  assert.ok(agents.includes("`npm run check`, `npm run arch`, `npm run test`, `npm run format`"));
  assert.ok(!agents.includes("read with `grep`"));
  writeRoleFiles({
    taskRoot,
    pluginRoot,
    role: "code-reviewer",
    category: "review",
    edits: false,
    repo: "app",
  });
  const reviewer = readFileSync(join(taskRoot, "AGENTS.md"), "utf8");
  assert.ok(reviewer.includes("read with `grep`, `cat`"));
  assert.ok(reviewer.includes("also in a pipeline"));
  assert.ok(!reviewer.includes("`git -C app mv`"));
  writeRoleFiles({
    taskRoot,
    pluginRoot,
    role: "software-engineer",
    category: "implementation",
    edits: true,
    repo: "app",
  });
  assert.equal(
    readFileSync(join(taskRoot, "REPORT.md"), "utf8"),
    readFileSync(join(pluginRoot, "templates/reports/implementation.md"), "utf8"),
  );
  assert.deepEqual(JSON.parse(readFileSync(join(taskRoot, ".claude", "settings.json"), "utf8")), {
    permissions: { defaultMode: "acceptEdits" },
  });
});

test("only the chosen skills are installed; a skill no longer chosen is removed on re-run", () => {
  const taskRoot = mkdtempSync(join(tmpdir(), "omi-skills-"));
  const o = {
    taskRoot,
    pluginRoot,
    role: "software-engineer" as const,
    category: "implementation" as const,
    edits: true,
    repo: "app",
  };
  writeRoleFiles({ ...o, skills: ["backend-implementation", "minimal-change"] });
  assert.deepEqual(installed(taskRoot), ["backend-implementation", "minimal-change"]);
  assert.ok(existsSync(join(taskRoot, ".claude", "skills", "minimal-change", "SKILL.md")));
  writeRoleFiles({ ...o, skills: ["backend-implementation"] });
  assert.deepEqual(installed(taskRoot), ["backend-implementation"]);
});

test("--skills: in the role's set accepted; outside it, a bad role or no reason refused", () => {
  const c = parseSkillChoice(
    pluginRoot,
    [
      "software-engineer=minimal-change, systematic-debugging",
      "code-reviewer=over-engineering-review",
    ],
    " small risky diff ",
  );
  assert.deepEqual(c, {
    byRole: {
      "software-engineer": ["minimal-change", "systematic-debugging"],
      "code-reviewer": ["over-engineering-review"],
    },
    reason: "small risky diff",
  });
  assert.equal(parseSkillChoice(pluginRoot, undefined, undefined), undefined);
  const refused = (flags: string[], reason = "why") =>
    assert.throws(() => parseSkillChoice(pluginRoot, flags, reason), { code: "USAGE_INVALID" });
  refused(["software-engineer=semantic-code-review"]); // a reviewer's skill
  refused(["software-engineer=no-such-skill"]);
  refused(["pilot=minimal-change"]);
  refused(["minimal-change"]);
  refused(["software-engineer=minimal-change"], " ");
});

test("step skills: defaults + choice; rework adds receiving-review-findings; escalation its skill", () => {
  const choice = { byRole: { "software-engineer": ["minimal-change"] }, reason: "x" };
  const be = { role: "software-engineer" as const, stepId: "implement" };
  assert.deepEqual(stepSkills(pluginRoot, { ...be, round: 1 }, choice), [
    ...roleSkills(pluginRoot, "software-engineer").default,
    "minimal-change",
  ]);
  assert.ok(stepSkills(pluginRoot, { ...be, round: 2 }).includes("receiving-review-findings"));
  const cr = { role: "code-reviewer" as const, stepId: "code-review", round: 2 };
  assert.ok(!stepSkills(pluginRoot, cr).includes("receiving-review-findings"), "read-only role");
  const sa = { role: "solution-architect" as const, round: 3 };
  assert.ok(stepSkills(pluginRoot, { ...sa, stepId: "architect" }).includes("root-cause-analysis"));
  assert.ok(!stepSkills(pluginRoot, { ...sa, stepId: "design" }).includes("root-cause-analysis"));
});

test("skill list: every role's sets and a description for every library skill", () => {
  const r = skillList(Role.options, pluginRoot);
  assert.equal(r.roles.length, Role.options.length);
  assert.equal(r.skills.length, 33);
  // Every skill a role names exists in the library, and no role names a removed one.
  const library = new Set(r.skills.map((s) => s.name));
  for (const role of r.roles) {
    for (const s of [...role.default, ...role.allowed])
      assert.ok(library.has(s), `${role.role}: ${s}`);
  }
  assert.deepEqual(
    r.roles.map((x) => x.role),
    [...Role.options],
  );
  assert.ok(
    r.skills.every((s) => /^Use (when|before|on) /.test(s.description)),
    "descriptions",
  );
});
