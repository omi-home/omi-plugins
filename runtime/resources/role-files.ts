// Role files of a task workspace (ADR-0002 D2/D4): before each agent run OMI writes, next to the
// clone, `AGENTS.md` (the role's rule pack, as listed in agents/<role>.md), `REPORT.md` (the step
// report template) and `.claude/settings.json`. Generated every time: never edit them by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { ReportCategory, Role } from "../core/contracts.ts";
import { OmiError } from "../core/errors/errors.ts";

const RULE = /^\$\{CLAUDE_PLUGIN_ROOT\}\/(resources\/[\w./-]+\.md)$/gm;

export function writeRoleFiles(o: {
  taskRoot: string;
  pluginRoot: string;
  role: Role;
  category: ReportCategory;
  /** Implementing roles may edit files in the clone. */
  edits: boolean;
}): void {
  const agent = readFileSync(join(o.pluginRoot, "agents", `${o.role}.md`), "utf8");
  const rules = [...agent.matchAll(RULE)].map((m) =>
    readFileSync(join(o.pluginRoot, m[1] as string), "utf8").trim(),
  );
  if (!rules.length) {
    throw new OmiError("CONFIG_INVALID", `agents/${o.role}.md lists no rule pack`);
  }
  writeFileSync(
    join(o.taskRoot, "AGENTS.md"),
    `<!-- Generated by OMI for role ${o.role}; rewritten before every run. -->\n# OMI ${o.role}\n\nThe product repository is the git directory next to this file: run git and repo commands there. Report with the structure of REPORT.md.\n\n${rules.join("\n\n---\n\n")}\n`,
  );
  writeFileSync(
    join(o.taskRoot, "REPORT.md"),
    readFileSync(join(o.pluginRoot, "templates", "reports", `${o.category}.md`)),
  );
  mkdirSync(join(o.taskRoot, ".claude"), { recursive: true });
  writeFileSync(
    join(o.taskRoot, ".claude", "settings.json"),
    `${JSON.stringify({ permissions: { defaultMode: o.edits ? "acceptEdits" : "default" } }, null, 2)}\n`,
  );
}
