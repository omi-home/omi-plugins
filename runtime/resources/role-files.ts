// Role files of a task workspace (ADR-0002 D2, ADR-0003 D5): before each agent run OMI writes, next
// to the clone, `AGENTS.md`, `REPORT.md` (the step report template) and `.claude/settings.json`.
// AGENTS.md holds only rules, the fixed part first for cache hits (DevTask-0064 #198):
// agents-md/core.md, editing.md or read-only.md, the repository line, agents-md/<role>.md, then the
// role's rule pack (`omi:rule-pack`, removed by DevTask-0065 #199). Generated every time.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AGENT_PACK } from "../adapters/claude/launch.ts";
import { READ_ONLY_ROLES, type ReportCategory, type Role } from "../core/contracts.ts";
import { OmiError } from "../core/errors/errors.ts";

/** Rule pack lines of agents/<role>.md (inside its `omi:rule-pack` comment). */
export const RULE = /^(resources\/[\w./-]+\.md)$/gm;

export function writeRoleFiles(o: {
  taskRoot: string;
  pluginRoot: string;
  role: Role;
  category: ReportCategory;
  /** Implementing roles may edit files in the clone. */
  edits: boolean;
  /** The clone as the agent addresses it from the task workspace (e.g. `omi-plugins`). */
  repo: string;
}): void {
  const agent = readFileSync(join(o.pluginRoot, AGENT_PACK, "agents", `${o.role}.md`), "utf8");
  const rules = [...agent.matchAll(RULE)].map((m) =>
    readFileSync(join(o.pluginRoot, m[1] as string), "utf8").trim(),
  );
  if (!rules.length) {
    throw new OmiError("CONFIG_INVALID", `agents/${o.role}.md lists no rule pack`);
  }
  const part = (name: string) =>
    readFileSync(join(o.pluginRoot, AGENT_PACK, "agents-md", `${name}.md`), "utf8").trim();
  const repoLine = `The product repository is \`${o.repo}/\`. Every Bash call starts in this workspace, so run git as \`git -C ${o.repo} <command>\` and the repository's own commands as \`cd ${o.repo} && <command>\` in one call: other forms are not permitted. Paths in your result are relative to the repository (\`src/x.ts\`, not \`${o.repo}/src/x.ts\`).`;
  const sections = [
    part("core"),
    part(READ_ONLY_ROLES.includes(o.role) ? "read-only" : "editing"),
    repoLine,
    part(o.role),
    ...rules,
  ];
  mkdirSync(join(o.taskRoot, ".claude"), { recursive: true });
  writeFileSync(
    join(o.taskRoot, "AGENTS.md"),
    `<!-- Generated by OMI; rewritten before every run. -->\n${sections.join("\n\n")}\n`,
  );
  writeFileSync(
    join(o.taskRoot, "REPORT.md"),
    readFileSync(join(o.pluginRoot, "templates", "reports", `${o.category}.md`)),
  );
  writeFileSync(
    join(o.taskRoot, ".claude", "settings.json"),
    `${JSON.stringify({ permissions: { defaultMode: o.edits ? "acceptEdits" : "default" } }, null, 2)}\n`,
  );
}
